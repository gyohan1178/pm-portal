       count(*) filter (where inv.location is not null
                          and inv.location <> '')              as 위치있음,
       count(*) filter (where inv.location is null
                           or inv.location = '')               as 위치없음
  from public.inventory inv
  join public.items i on i.id = inv.item_id
 where i.std_code like 'ED-%';
