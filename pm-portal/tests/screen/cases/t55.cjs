const {chromium}=require('playwright');
let pass=0,fail=0; const ok=(c,m,x)=>{ if(c){pass++;console.log('  ✓',m)}else{fail++;console.log('  ✗',m,x===undefined?'':JSON.stringify(x))} };
const U=(q,r)=>`http://localhost:8765/app.html?cyc=1&cycp=1&${q}&r=${encodeURIComponent(r)}`;
const open=async(p,n)=>{await p.click(`[data-cycle-todo="${n}"] >> text=칸 보기`).catch(()=>{});await p.waitForTimeout(700)};
const T=(p,s)=>p.$eval(s,e=>e.innerText.replace(/\s+/g,' ')).catch(()=>'');
(async()=>{const b=await chromium.launch();const errs=[];
const pg=async(q,r)=>{const p=await b.newPage({viewport:{width:1400,height:1000}});p.on('pageerror',e=>errs.push(e.message));await p.goto(U(q,r));await p.waitForTimeout(2200);return p};
console.log('① 배솔 — 김교한 렉을 거꾸로');
let p=await pg('asbae=1&cyd=10','/todo');
await open(p,'배솔');
let cells=await p.$$eval('[data-cycle-todo="배솔"] [data-cycle-cell]',a=>a.map(e=>e.dataset.cycleCell));
ok(cells[0]==='N2-03-3'&&cells[1]==='N2-03-2','배솔 오늘 칸 = N2 맨 뒤부터 (N2-03-3 → N2-03-2)',cells);
await p.close();
p=await pg('cyd=10','/todo');
await open(p,'김교한');
cells=await p.$$eval('[data-cycle-todo="김교한"] [data-cycle-cell]',a=>a.map(e=>e.dataset.cycleCell));
ok(cells.includes('N2-01-2')&&cells.indexOf('N2-01-2')<cells.indexOf('N2-03-3'),'김교한은 그대로 앞에서부터',cells);
await p.close();
console.log('② 배솔이 2칸 센 날 — 김교한 숫자엔 안 들어감');
p=await pg('baecnt=1&cyd=10','/todo');
let row=await T(p,'[data-cycle-todo="김교한"]');
ok(/2 \/ 10칸/.test(row),'김교한 「2 / 10칸」 (배솔 2칸 안 합침 — 예전엔 4)',row);
await open(p,'김교한');
cells=await p.$$eval('[data-cycle-todo="김교한"] [data-cycle-cell]',a=>a.map(e=>e.dataset.cycleCell));
ok(cells.length>0&&!cells.includes('N2-03-3')&&!cells.includes('N2-03-2'),'배솔이 오늘 센 칸은 김교한 남은 목록에서 빠짐',cells);
await p.close();
p=await pg('asbae=1&baecnt=1&cyd=10','/todo');
await p.click('text=펼치기').catch(()=>{}); await p.waitForTimeout(600);
row=await T(p,'[data-cycle-todo="배솔"]');
ok(/2 \/ 2칸/.test(row),'배솔 「2 / 2칸」',row);
await p.close();
ok(!errs.length,'페이지 오류 없음',errs);
console.log(`\n${pass} 통과 / ${fail} 실패`);await b.close();process.exit(fail?1:0)})();
