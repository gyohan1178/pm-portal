// v4.199.0 — 수주대장 PO 「🔍 자재 점검」: 판정 표 · 문제 없음 → 가능 회신 · 문제 있음 → 조건부(사유 미리 채움 · 문제 줄만) · 발주 담기 · 변경 이력 · SQL 전 안내
const { chromium } = require('playwright')
let pass = 0, fail = 0
const ok = (c, m, x) => { if (c) { pass++; console.log('  ✓ ' + m) } else { fail++; console.log('  ✗ ' + m + ' → ' + JSON.stringify(x ?? '').slice(0, 500)) } }
;(async () => {
  const b = await chromium.launch(); const errs = []
  const open = async (q, w = 1366) => {
    const p = await b.newPage({ viewport: { width: w, height: 800 } }); p.on('pageerror', e => errs.push(e.message.slice(0, 150)))
    await p.clock.setFixedTime(new Date('2026-11-16T01:00:00Z'))
    await p.goto('http://localhost:8765/app.html?unconf=1&' + q + '&r=' + encodeURIComponent('/orders')); await p.waitForTimeout(3000)
    await p.locator('text=UC-ED-NEAR').first().click(); await p.waitForTimeout(800)
    if (!(await p.locator('[data-po-drawer]').count())) { await p.locator('button:has-text("PO 별"), [data-view="po"]').first().click().catch(() => {}); await p.waitForTimeout(500); await p.locator('text=UC-ED-NEAR').first().click(); await p.waitForTimeout(800) }
    return p
  }
  // 0) 한 단계 — 11월 전 PO 는 미확인에서 빠지고 아래 줄 (기본 자료 VM 10월 PO + 시험 10월 PO = 2건)
  let p = await b.newPage({ viewport: { width: 1366, height: 800 } }); p.on('pageerror', e => errs.push(e.message.slice(0, 150)))
  await p.clock.setFixedTime(new Date('2026-11-16T01:00:00Z'))
  await p.goto('http://localhost:8765/app.html?unconf=1&matchk=2&r=' + encodeURIComponent('/orders')); await p.waitForTimeout(3000)
  const kp = (await p.locator('[data-kpi="미확인"]').innerText()).replace(/\n/g, ' ')
  ok(/\b3\b/.test(kp) && /품목 19줄/.test(kp), '미확인 3 (10월 PO 안 셈)', kp)
  ok(/11월 전 PO 회신 없음 2건/.test(await p.locator('[data-old-noreply]').innerText().catch(() => '')), '11월 전 PO 회신 없음 2건 따로')
  ok(await p.locator('[data-kpi="회신 대기"]').count() === 0, '회신 대기 지표 없음')
  await p.click('[data-old-noreply-btn]'); await p.waitForTimeout(500)
  const tm = await p.locator('main').innerText()
  ok(/UC-OLD-OCT/.test(tm) && !/UC-ED-NEAR/.test(tm), '보기: 11월 전 PO 만')
  await p.close()
  // 1) 부족 있음
  p = await open('matchk=1')
  ok(await p.locator('[data-po-drawer]').count() === 1, 'PO 창 열림')
  await p.click('[data-mat-check]'); await p.waitForTimeout(1200)
  const head = await p.locator('[data-mc]').innerText()
  const h1 = head.replace(/\n/g, ' ')
  ok(/부족\s*2/.test(h1) && /입고 늦음\s*1/.test(h1) && /뒤 PO 영향\s*1/.test(h1) && /충분\s*9/.test(h1), '지표: 부족 2 · 입고 늦음 1 · 뒤 PO 영향 1 · 충분 9', h1.slice(0, 400))
  ok(/PO-LATER-1 몫 3개 모자람/.test(await p.locator('[data-mc-row="ED-SQZ"]').innerText()), '뒤 PO 영향 줄: 어느 PO 몫 몇 개')
  ok(await p.locator('[data-mc-ed-note]').count() === 1, 'Edwards BOM 참고용 안내')
  ok(await p.locator('[data-mc-row]').count() === 5, '처음엔 부족 · 늦음 · BOM 없음 · 뒤 PO 영향만 (충분 8 · 하네스 접힘)', await p.locator('[data-mc-row]').count())
  const order = await p.locator('[data-mc-row]').evaluateAll((els) => els.map((e) => e.dataset.mcVerdict))
  ok(order[0] === 'short' && order[2] === 'late', '부족이 맨 위', order)
  await p.click('[data-mc-fold]'); await p.waitForTimeout(200)
  ok(await p.locator('[data-mc-row]').count() === 14, '펼치면 충분 · 하네스까지 14줄')
  ok(await p.locator('[data-mc-ok]').isDisabled(), '부족 있으면 「문제 없음」 못 누름')
  // 발주 담기만
  await p.click('[data-mc-cart-only]'); await p.waitForTimeout(800)
  const cart = await p.evaluate(() => window.__S.DATA.pm_po_cart || [])
  ok(cart.length === 2 && cart.some((c) => c.item_id === 'mi-ED-SHORT1' && c.qty === 3 && c.customer_id === 'cid-ed'), '부족 2품목 담기 (모자란 수량 · 고객사)', cart)
  // 문제 있음 → 조건부 (문제 줄만)
  await p.click('[data-mc-issue-open]'); await p.waitForTimeout(400)
  const memo = await p.inputValue('[data-mc-memo]')
  ok(/부족 2품목/.test(memo) && /ED-SHORT1 3개 \(발주 없음\)/.test(memo) && /ED-SHORT2 1개 \(01\/20 입고\)/.test(memo) && /입고 늦음 1품목 — ED-LATE1 12\/22/.test(memo) && /BOM 없음 2줄/.test(memo) && /뒤 PO 영향 1품목 — .*ED-SQZ 3개 \(PO-LATER-1\)/.test(memo), '사유 미리 채움 (뒤 PO 영향 포함)', memo)
  ok(await p.inputValue('[data-mc-date]') === '', '발주 없는 부족이 있으면 날짜 제안 안 함')
  await p.fill('[data-mc-date]', '2027-01-27')
  await p.selectOption('[data-mc-scope]', 'aff')
  await p.uncheck('[data-mc-cart]')
  await p.click('[data-mc-issue-save]'); await p.waitForTimeout(1500)
  const ls = await p.evaluate(() => window.__S.DATA.pm_order_line.filter((l) => l.order_id === 'uo2'))
  const by = (r) => ls.filter((l) => l.reply === r).map((l) => l.id).sort()
  ok(JSON.stringify(by('조건부')) === JSON.stringify(['ue2_1', 'ue2_2', 'ue2_3', 'ue2_4', 'ue2_5']) && by('가능').length === 10, '문제 줄 5개 조건부 · 나머지 10 가능', [by('조건부'), by('가능').length])
  const l1 = ls.find((l) => l.id === 'ue2_1')
  ok(l1.reply_date === '2027-01-27' && /부족 2품목/.test(l1.reply_memo || ''), '조건부 날짜 · 사유 저장', l1)
  const o2 = await p.evaluate(() => window.__S.DATA.pm_order.find((o) => o.id === 'uo2'))
  ok(!!o2.confirmed_at, 'PO 확인 처리됨')
  const ch = await p.evaluate(() => (window.__S.DATA.pm_order_change || []).filter((c) => c.field === 'mat_check'))
  ok(ch.length === 1 && /부족 2 \(ED-SHORT1, ED-SHORT2\)/.test(ch[0].after_val) && /조건부 5줄 · 가능 10줄/.test(ch[0].after_val) && /뒤 PO 영향 1/.test(ch[0].after_val), '변경 이력 「자재 점검」', ch)
  ok(await p.locator('[data-mc]').count() === 0, '저장 뒤 점검 창 닫힘')
  ok((await p.evaluate(() => (window.__S.DATA.pm_po_cart || []).length)) === 2, '담기 끈 채 저장 → 더 안 담김')
  await p.close()
  // 2) 문제 없음
  p = await open('matchk=2')
  await p.click('[data-mat-check]'); await p.waitForTimeout(1200)
  ok(!(await p.locator('[data-mc-ok]').isDisabled()), '문제 없으면 「가능」 누를 수 있음')
  ok(await p.locator('[data-mc-cart-only]').count() === 0, '부족 없으면 담기 버튼 없음')
  await p.click('[data-mc-ok]'); await p.waitForTimeout(1500)
  const ls2 = await p.evaluate(() => window.__S.DATA.pm_order_line.filter((l) => l.order_id === 'uo2'))
  ok(ls2.every((l) => l.reply === '가능' && l.reply_memo === '자재 점검 이상 없음'), '15줄 모두 가능 · 메모', ls2.map((l) => l.reply))
  await p.close()
  // 3) SQL 전
  p = await open('x=1')
  await p.click('[data-mat-check]'); await p.waitForTimeout(1200)
  const er = await p.locator('[data-mc-error]').innerText().catch(() => '')
  ok(/수주확인_자재점검_반영_261116/.test(er), 'SQL 없으면 실행 안내', er)
  await p.close()
  // 4) 휴대폰 폭
  p = await open('matchk=1', 390)
  await p.click('[data-mat-check]'); await p.waitForTimeout(1200)
  const sw = await p.evaluate(() => [document.documentElement.scrollWidth, innerWidth]); ok(sw[0] <= sw[1], '휴대폰 가로 넘침 없음 (표는 안에서 밀림)', sw)
  await p.screenshot({ path: '/tmp/jsportal-test/out/matchk_m.png' })
  await p.close()
  p = await open('matchk=1'); await p.click('[data-mat-check]'); await p.waitForTimeout(1200); await p.screenshot({ path: '/tmp/jsportal-test/out/matchk.png' })
  await p.click('[data-mc-issue-open]'); await p.waitForTimeout(300); await p.screenshot({ path: '/tmp/jsportal-test/out/matchk_issue.png' })
  console.log(`pass=${pass} fail=${fail}`, 'errs', errs)
  await b.close()
})()
