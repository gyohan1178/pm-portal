// v4.130.0 — 기타 고객사의 BOM 기준 고객사 (제스코 → AXCELIS BOM)
const {chromium}=require('playwright');
const base='http://localhost:8765/app.html';
let pass=0, fail=0; const ok=(c,m,x)=>{ if(c){pass++;console.log('  ✓',m)} else {fail++;console.log('  ✗',m, x===undefined?'':'→ '+JSON.stringify(x))} };
(async()=>{const b=await chromium.launch();
const p=await b.newPage({viewport:{width:1440,height:1000}});const errs=[];p.on('pageerror',e=>errs.push(e.message));p.on('dialog',d=>d.accept());
await p.goto(`${base}?q99=1&r=${encodeURIComponent('/sales-quote')}`);await p.waitForTimeout(1800);
const newRfq=async(name,title,paste,ref)=>{
  await p.click('[data-rfq-new]'); await p.waitForTimeout(300);
  await p.selectOption('[data-rfq-cs]','__etc'); await p.waitForTimeout(150);
  await p.fill('[data-rfq-etc]',name); await p.waitForTimeout(150);
  const def=await p.$eval('[data-rfq-ref]',e=>e.value);
  if(ref!==undefined) await p.selectOption('[data-rfq-ref]',ref);
  await p.fill('[data-rfq-title]',title); await p.fill('[data-rfq-paste]',paste);
  await p.click('[data-rfq-save]'); await p.waitForTimeout(2000);
  const R=await p.evaluate((t)=>window.__S.DATA.pm_rfq.find(x=>x.title===t),title);
  const L=await p.evaluate((id)=>window.__S.DATA.pm_rfq_line.filter(x=>x.rfq_id===id),R&&R.id);
  return {def,R,L};
};
console.log('① 제스코 — 기본값 AXCELIS');
let {def,R,L}=await newRfq('(주)제스코','LE Spare 제스코','110153030\tASSY\t\t1');
ok(def==='ax','이름 넣으면 「BOM 기준: AXCELIS」 미리 골라짐',def);
ok(R&&R.customer_code==='(주)제스코'&&!R.customer_id,'고객사는 이름 그대로 · id 없음');
ok(L.length===1&&L[0].kind==='assy'&&L[0].std_code==='AX-110153030'&&L[0].project_id==='pj1','AXCELIS 등록 BOM(AX-110153030)으로 점검 — 예전엔 「BOM · 품목 없음」',L[0]);
console.log('② 처음 보는 업체 — 자동(전체에서 찾기)');
({def,R,L}=await newRfq('신규협력사','자동 찾기','110153030\t\t\t2'));
ok(def==='','처음 보는 이름은 「자동」',def);
ok(L[0]?.kind==='assy'&&L[0].std_code==='AX-110153030','자동 — 등록된 BOM 에서 찾음',L[0]);
console.log('③ 남일 — 기본값 Edwards (AX BOM 은 안 찾음)');
({def,R,L}=await newRfq('남일','남일 견적','110153030\t\t\t1'));
ok(def==='ed','남일 → 「BOM 기준: Edwards」',def);
ok(L[0]?.kind==='none','Edwards 에 없는 품번 → BOM 필요 (AX BOM 을 잘못 끌어오지 않음)',L[0]);
const btn=await p.textContent('tr:has-text("남일 견적") [data-rfq-act="bom"]').catch(()=>'');
ok(/BOM 올리기 \(ED\)/.test(btn),'「🧬 BOM 올리기 (ED)」 버튼',btn);
console.log('④ 고른 기준 기억');
({def,R,L}=await newRfq('한빛테크','기억 확인','110153030\t\t\t1','ed'));
const st=await p.evaluate(()=>JSON.stringify((window.__S.DATA.pm_settings||[]).find(x=>x.key==='etc_customer_ref')?.value||null));
ok(/한빛테크.*ed/.test(st),'pm_settings 에 「한빛테크 → ed」 저장',st);
await p.click('[data-rfq-new]'); await p.waitForTimeout(300); await p.selectOption('[data-rfq-cs]','__etc'); await p.fill('[data-rfq-etc]','한빛 테크'); await p.waitForTimeout(400);
ok(await p.$eval('[data-rfq-ref]',e=>e.value)==='ed','다음 접수에 「한빛 테크」(띄어쓰기 달라도) → Edwards 미리 골라짐');
await p.screenshot({path:'etc_ref_form.png',clip:{x:220,y:200,width:1220,height:360}});
await p.click('[data-rfq-form] >> text=✕ 닫기');
console.log('⑤ 견적 작성 — BOM 원가로');
const L0=await p.evaluate(()=>window.__S.DATA.pm_rfq_line.find(x=>x.std_code==='AX-110153030'&&x.pn==='110153030'));console.log('   line',JSON.stringify(L0));
const acts=await p.$$eval('tr:has-text("LE Spare 제스코") [data-rfq-act]',a=>a.map(x=>x.dataset.rfqAct));console.log('   acts',acts);
await p.evaluate(()=>{ window.__S.DATA.items.forEach(i=>{ if(i.purchase_price==null) i.purchase_price=100 }) });
await p.click('tr:has-text("LE Spare 제스코") [data-rfq-act="recheck"]'); await p.waitForTimeout(2000);
await p.click('tr:has-text("LE Spare 제스코") [data-rfq-act="write"]'); await p.waitForTimeout(2500);
ok(await p.locator('[data-etc-cust]').count()===1,'「기타 고객사 · (주)제스코」');
const row=await p.$eval('.qs-edit tbody tr.align-top',e=>e.innerText.replace(/\s+/g,' ')).catch(()=>'');
ok(/ASSY/.test(row)&&/부품 \d/.test(row),'견적 줄이 ASSY · 부품 n (AXCELIS BOM 전개)',row.slice(0,200));
ok(errs.length===0,'오류 없음',errs);
console.log(`\n${pass} 통과 / ${fail} 실패`);await b.close();process.exit(fail?1:0)})();
