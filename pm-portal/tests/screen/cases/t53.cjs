// v4.123.0 자재요청 부분 불출
const { chromium } = require('playwright')
let pass = 0, fail = 0
const ok = (c, m) => { if (c) { pass++; console.log('  ✔', m) } else { fail++; console.log('  ✘', m) } }
;(async () => {
  const br = await chromium.launch()
  const pg = await br.newPage({ viewport: { width: 1440, height: 1000 } })
  const errs = []; pg.on('pageerror', e => errs.push(e.message))
  await pg.goto('http://localhost:8765/app.html?mr=1&r=' + encodeURIComponent('/material-request')); await pg.waitForTimeout(2500)
  const S = () => pg.evaluate(() => ({ rows: window.__S.DATA.mr_rows.map(r => ({ id: r.id, st: r.status, iss: r.issued_qty ?? null })), stock: { ...window.__S.DATA.mr_stock } }))
  const rowBtn = async (code) => { const rows = pg.locator(`button[title^="이 품목만 불출"]`); const n = await rows.count(); for (let i = 0; i < n; i++) { const b = rows.nth(i); const t = await b.evaluate(el => el.closest('[class*="grid"], tr, div')?.parentElement?.textContent || ''); if (t.includes(code)) return b } return null }
  const toasts = async () => (await pg.textContent('body'))

  console.log('1) 줄 [불출] → 수량 칸 (처음엔 남은 수량)')
  let b = await rowBtn('AX-5100052'); ok(!!b, '불출 버튼 찾음')
  await b.click(); await pg.waitForTimeout(400)
  const inp = pg.locator('[data-confirm-input]')
  ok(await inp.count() === 1 && await inp.getAttribute('type') === 'number', '숫자 칸')
  ok(await inp.inputValue() === '20', '처음 값 = 남은 20: ' + await inp.inputValue())
  ok((await pg.textContent('[data-confirm-dialog]')).includes('남은 20'), '창에 요청 20 · 남은 20')
  await inp.fill('25'); await pg.click('[data-confirm-ok]'); await pg.waitForTimeout(200)
  ok((await pg.textContent('[data-confirm-dialog]')).includes('남은 수량(20)보다'), '25 → 남은 수량 넘음 안내 (창 유지)')
  await inp.fill('0'); await pg.click('[data-confirm-ok]'); await pg.waitForTimeout(200)
  ok((await pg.textContent('[data-confirm-dialog]')).includes('0보다 크게'), '0 → 안내')
  await inp.fill('8'); await inp.press('Enter'); await pg.waitForTimeout(1200)
  let s = await S()
  ok(s.rows.find(r => r.id === 101).iss === 8 && s.rows.find(r => r.id === 101).st === '확인' && s.stock.p1 === 7, '8 불출 → 8/20 · 진행 중 · 재고 15→7')
  ok((await toasts()).includes('남은 12'), '알림 「8EA 불출 · 남은 12 (진행 중)」')
  ok(await pg.locator('[data-mr-partial]').filter({ hasText: '8/20' }).count() >= 1, '줄에 「불출 8/20」')
  const rpc = await pg.evaluate(() => window.__S.RPC.filter(x => x.fn === 'pm_request_issue_part').map(x => x.args))
  ok(rpc.length === 1 && rpc[0].p_id === 101 && rpc[0].p_qty === 8 && rpc[0].p_force === false, 'pm_request_issue_part(101, 8, false)')

  console.log('2) 이어서 불출 → 남은 12, 재고 7 → 강제 여부 물음')
  b = await rowBtn('AX-5100052'); await b.click(); await pg.waitForTimeout(400)
  ok(await inp.inputValue() === '12', '처음 값 = 남은 12')
  ok((await pg.textContent('[data-confirm-dialog]')).includes('이미 불출 8'), '창에 이미 불출 8')
  await pg.click('[data-confirm-ok]'); await pg.waitForTimeout(800)
  const d2 = await pg.textContent('[data-confirm-dialog]').catch(() => '')
  ok(d2.includes('재고가 모자랍니다') && d2.includes('재고 부족(7/12)'), '재고 부족 → 강제 불출 물음')
  await pg.click('[data-confirm-ok]'); await pg.waitForTimeout(1200)
  s = await S()
  ok(s.rows.find(r => r.id === 101).st === '완료' && s.rows.find(r => r.id === 101).iss === 20 && s.stock.p1 === -5, '강제 → 완료 20/20 · 재고 -5')

  console.log('3) 일부 불출 줄 → 위쪽 일괄 불출은 남은 수량만')
  b = await rowBtn('AX-6200111'); await b.click(); await pg.waitForTimeout(400)
  await inp.fill('1'); await pg.click('[data-confirm-ok]'); await pg.waitForTimeout(1200)
  s = await S(); ok(s.rows.find(r => r.id === 102).iss === 1 && s.stock.p2 === 9, '102: 1/2 · 재고 9')
  // 체크 → 되돌리기 버튼 보임 (부분 불출 줄)
  const row102 = pg.locator('[data-req-item]', { hasText: 'AX-6200111' }).first()
  await row102.click({ position: { x: 10, y: 12 } }); await pg.waitForTimeout(500)
  const undoBtn = pg.locator('button', { hasText: '완료 되돌리기' })
  ok(await undoBtn.count() === 1, '일부 불출 줄을 고르면 「완료 되돌리기」 보임')
  await pg.locator('button', { hasText: '불출 처리' }).first().click(); await pg.waitForTimeout(400)
  const d3 = await pg.textContent('[data-confirm-dialog]')
  ok(d3.includes('남은 1/2'), '일괄 불출 창에 「남은 1/2」')
  await pg.keyboard.press('Escape'); await pg.waitForTimeout(300)

  console.log('4) 일부 불출 줄 되돌리기')
  await undoBtn.click(); await pg.waitForTimeout(400)
  const d4 = await pg.textContent('[data-confirm-dialog]')
  ok(d4.includes('부분 불출 1/2') && d4.includes('출고를 지우고 재고를 되돌립니다'), '되돌리기 창: 부분 불출 1/2 · 재고 되돌림 경고')
  await pg.click('[data-confirm-ok]'); await pg.waitForTimeout(1200)
  s = await S(); ok(s.rows.find(r => r.id === 102).iss === null && s.stock.p2 === 10 && s.rows.find(r => r.id === 102).st === '확인', '102: 불출 지움 · 재고 10 복구')

  console.log('5) 코드 없는 줄에는 [불출] 버튼 없음 (그대로)')
  ok(!(await rowBtn('TERMINAL RING')), '코드 없는 줄 불출 버튼 없음')
  ok(errs.length === 0, '화면 오류 없음 ' + errs.slice(0, 2).join(' | '))
  console.log(`\n결과: 통과 ${pass} · 실패 ${fail}`)
  await br.close(); process.exit(fail ? 1 : 0)
})()
